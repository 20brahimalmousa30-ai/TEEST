/**
 * تطبيع رقم الجوّال إلى صيغةٍ قياسيّة واحدة `05XXXXXXXX`.
 *
 * لماذا؟ كانت الأرقام تُخزَّن كما تُلصَق (من واتساب/الآيفون) فتحمل محارف اتجاهٍ خفيّة
 * (U+2066/U+2069…) ومسافاتٍ و«+966» وأرقاماً هنديّة (٠-٩). وبما أنّ الدخول يطابق الرقم
 * حرفيّاً، كان أصحاب تلك الأرقام يُمنعون من الدخول. نُطبّع عند الكتابة وعند الدخول معاً.
 */
export function normalizePhone(raw: string | null | undefined): string {
  if (!raw) return "";
  // ١) حوّل الأرقام العربية-الهنديّة (٠-٩) والفارسيّة (۰-۹) إلى لاتينيّة.
  const latin = raw
    .replace(/[٠-٩]/g, d => String(d.charCodeAt(0) - 0x0660))
    .replace(/[۰-۹]/g, d => String(d.charCodeAt(0) - 0x06F0));
  // ٢) أبقِ الأرقام فقط (يُزيل المسافات و«+» ومحارف الاتجاه الخفيّة وأيّ رموز).
  let d = latin.replace(/\D/g, "");
  // ٣) وحِّد بادئة الدولة إلى الصيغة المحلّيّة: 00966/966 → 0، و5XXXXXXXX → 05XXXXXXXX.
  if (d.startsWith("00")) d = d.slice(2);
  if (d.startsWith("966")) d = d.slice(3);
  if (d.length === 9 && d.startsWith("5")) d = "0" + d;
  return d;
}
