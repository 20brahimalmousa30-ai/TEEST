def _fill(template: str, match: re.Match) -> str:
    """يعوّض {1} و{2} بالمجموعات الملتقطة، ويتجاهل الفارغة."""
    text = template
    for index in range(1, (match.re.groups or 0) + 1):
        try:
            value = (match.group(index) or "").strip()
        except IndexError:
            value = ""
        text = text.replace(f"{{{index}}}", value)
    return text


def explain_command(command: str) -> str:
    """يشرح بالعربية ماذا سيفعل أمر الصدفة هذا."""
    text = (command or "").strip()
    if not text:
        return "طلب فارغ — تعذّرت قراءته"

    for pattern, template in INTENT_PATTERNS:
        match = pattern.search(text)
        if match:
            return _fill(template, match)

    return f"تنفيذ «{text[:70]}» — لم أتعرّف على وظيفة هذا الأمر"


def explain_request(tool: str, argument: str) -> str:
    """يشرح بالعربية ماذا يريد Claude Code من هذا الطلب."""
    name = (tool or "").strip().lower()
    arg = (argument or "").strip()

    if name in TOOL_INTENTS:
        return TOOL_INTENTS[name].replace("{arg}", arg[:70])

    # bash / task / بلا أداة ⇒ يُشرح الأمر نفسه
    return explain_command(arg)
